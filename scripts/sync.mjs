// Rebuilds subgraph.yaml, networks.json and the ABIs from a contracts deployment file.
//   node scripts/sync.mjs ../MSTRX robinhood robinhood-mainnet
import fs from 'node:fs';
import path from 'node:path';

const repo = process.argv[2] ?? '../MSTRX';
const deploymentName = process.argv[3] ?? 'robinhoodTestnet';
const graphNetwork = process.argv[4] ?? process.env.GRAPH_NETWORK ?? 'robinhood';

const deploymentFile = path.join(repo, 'deployments', `${deploymentName}.json`);
if (!fs.existsSync(deploymentFile)) {
  console.error(`No deployment at ${deploymentFile}`);
  process.exit(1);
}
const deployment = JSON.parse(fs.readFileSync(deploymentFile, 'utf8'));
const startBlock = deployment.startBlock;

// Only the NAV history is indexed; the app reads everything else live from chain.
const SOURCES = [
  {
    name: 'Treasury',
    artifact: 'core/Treasury.sol/Treasury',
    address: 'treasury',
    file: 'nav',
    // Carries both the BTC balance and the backing supply.
    events: [['TreasuryUpdated(uint256,uint256,uint256)', 'handleTreasuryUpdated']],
    entities: ['NavPoint'],
  },
];

fs.mkdirSync('abis', { recursive: true });
const writtenAbis = new Set();
for (const source of SOURCES) {
  const abiName = source.abiName ?? source.name;
  if (writtenAbis.has(abiName)) continue;
  const artifactPath = path.join(repo, 'artifacts/contracts', `${source.artifact}.json`);
  if (!fs.existsSync(artifactPath)) {
    console.error(`  MISSING artifact ${source.artifact}`);
    continue;
  }
  const { abi } = JSON.parse(fs.readFileSync(artifactPath, 'utf8'));
  fs.writeFileSync(path.join('abis', `${abiName}.json`), `${JSON.stringify(abi, null, 2)}\n`);
  writtenAbis.add(abiName);
  console.log(`  abi   ${abiName}.json`);
}

// Called from the handler, not indexed.
const oracleArtifact = path.join(repo, 'artifacts/contracts/adapters/ProtocolOracle.sol/ProtocolOracle.json');
if (fs.existsSync(oracleArtifact)) {
  const { abi } = JSON.parse(fs.readFileSync(oracleArtifact, 'utf8'));
  fs.writeFileSync(path.join('abis', 'ProtocolOracle.json'), `${JSON.stringify(abi, null, 2)}\n`);
  console.log('  abi   ProtocolOracle.json  (read from handlers, not indexed)');
}

const address = (key) => {
  const value = deployment.addresses[key];
  if (!value) throw new Error(`${deploymentFile} has no "${key}"`);
  return value;
};

const dataSource = (source) => {
  const abiName = source.abiName ?? source.name;
  return `  - kind: ethereum
    name: ${source.name}
    network: ${graphNetwork}
    source:
      address: "${address(source.address)}"
      abi: ${abiName}
      startBlock: ${startBlock}
    mapping:
      kind: ethereum/events
      apiVersion: 0.0.9
      language: wasm/assemblyscript
      entities:
${source.entities.map((e) => `        - ${e}`).join('\n')}
      abis:
${[abiName, 'ProtocolOracle', 'Treasury']
  .filter((n, i, all) => all.indexOf(n) === i)
  .map((n) => `        - name: ${n}\n          file: ./abis/${n}.json`)
  .join('\n')}
      eventHandlers:
${source.events.map(([sig, handler]) => `        - event: ${sig}\n          handler: ${handler}`).join('\n')}
      file: ./src/${source.file}.ts`;
};

const manifest = `# Generated by \`node scripts/sync.mjs\`. Do not edit by hand: re-run it after a deployment.
#
# Deployment: ${deployment.deployment} (${deployment.network}), profile ${deployment.profile}
# Indexing from block ${startBlock}, which is the block before anything of ours existed.
specVersion: 1.3.0
indexerHints:
  prune: auto
schema:
  file: ./schema.graphql
dataSources:
${SOURCES.map(dataSource).join('\n')}
`;

fs.writeFileSync('subgraph.yaml', manifest);
console.log(`\n  manifest  subgraph.yaml  (${SOURCES.length} data sources, network ${graphNetwork})`);

const networks = {
  [graphNetwork]: Object.fromEntries(
    SOURCES.map((s) => [s.name, { address: address(s.address), startBlock }]),
  ),
};
fs.writeFileSync('networks.json', `${JSON.stringify(networks, null, 2)}\n`);
console.log('  networks  networks.json');

fs.mkdirSync('src/generated-config', { recursive: true });
fs.writeFileSync(
  'src/generated-config/addresses.ts',
  `// Generated by \`node scripts/sync.mjs\`. Do not edit.
import { Address } from '@graphprotocol/graph-ts';

export const PROTOCOL_ORACLE = Address.fromString('${address('protocolOracle')}');
export const STRAT_TOKEN = Address.fromString('${address('strat')}');
export const BTC_TOKEN = Address.fromString('${address('btc')}');
export const TREASURY = Address.fromString('${address('treasury')}');
`,
);
console.log('  config    src/generated-config/addresses.ts');
